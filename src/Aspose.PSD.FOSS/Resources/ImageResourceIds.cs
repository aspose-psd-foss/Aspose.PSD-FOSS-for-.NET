namespace Aspose.PSD.FileFormats.Psd;

/// <summary>
/// Provides common PSD image resource identifiers used by tests and fixtures.
/// </summary>
internal static class ImageResourceIds
{
    /// <summary>
    /// The PSD resource identifier historically used for the global lighting angle metadata.
    /// </summary>
    public const short GlobalAngle = 1037;

    /// <summary>
    /// The PSD resource identifier historically used for an embedded ICC profile payload.
    /// </summary>
    public const short IccProfile = 1039;

    /// <summary>
    /// The PSD resource identifier historically used for the intentionally-untagged ICC profile flag.
    /// </summary>
    public const short IccUntaggedProfile = 1041;
}
