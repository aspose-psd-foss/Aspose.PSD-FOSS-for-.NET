namespace Aspose.PSD.FileFormats.Psd;

/// <summary>
/// Represents the supported PSD container versions.
/// </summary>
public enum PsdVersion : byte
{
    /// <summary>
    /// Standard PSD document format.
    /// </summary>
    Psd = 1,

    /// <summary>
    /// Large-document PSB format.
    /// </summary>
    Psb = 2
}
